import ExcelJS from 'exceljs';

const pesoFormat = '₱#,##0.00';
const percentFormat = '0.0%';

function safeText(value) {
  const text = String(value ?? '');
  return /^[=+\-@]/.test(text) ? `'${text}` : text;
}

function amount(centavos) {
  return Number(centavos || 0) / 100;
}

function minutesBetween(start, end) {
  if (!start || !end) return null;
  const startMs = new Date(start).getTime();
  const endMs = new Date(end).getTime();
  if (!Number.isFinite(startMs) || !Number.isFinite(endMs) || endMs < startMs) return null;
  return (endMs - startMs) / 60_000;
}

function addHeader(sheet, values) {
  const row = sheet.addRow(values);
  row.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  row.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF102440' } };
  row.alignment = { vertical: 'middle', wrapText: true };
  row.height = 24;
  return row;
}

function styleSheet(sheet, widths, filterEnd) {
  sheet.columns = widths.map((width) => ({ width }));
  sheet.views = [{ state: 'frozen', ySplit: 1 }];
  if (filterEnd) sheet.autoFilter = `A1:${filterEnd}1`;
}

function addTitle(sheet, title, period, generatedBy, columnEnd = 'H') {
  sheet.mergeCells(`A1:${columnEnd}1`);
  sheet.getCell('A1').value = title;
  sheet.getCell('A1').font = { bold: true, size: 16, color: { argb: 'FF102440' } };
  sheet.getCell('A2').value = `Period: ${period.from} to ${period.to}`;
  sheet.getCell('A3').value = `Generated by: ${safeText(generatedBy)}`;
  sheet.getCell('A4').value = 'Timezone: Asia/Manila business dates. Timestamps are UTC.';
  sheet.getCell('A4').font = { italic: true, color: { argb: 'FF526177' } };
}

