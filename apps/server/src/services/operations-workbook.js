function addServiceTimesSheet(workbook, orders) {
  const sheet = workbook.addWorksheet('Service Times');
  addHeader(sheet, [
    'Order number',
    'Business date',
    'Payment wait (min)',
    'Preparation (min)',
    'Handoff (min)',
    'Total time (min)',
    'Data quality',
  ]);
  for (const order of orders.filter((item) => item.status === 'completed')) {
    const values = [
      minutesBetween(order.created_at, order.payment_confirmed_at),
      minutesBetween(order.preparing_at, order.ready_at),
      minutesBetween(order.ready_at, order.completed_at),
      minutesBetween(order.created_at, order.completed_at),
    ];
    const row = sheet.addRow([
      safeText(order.order_number),
      safeText(order.business_date),
      ...values,
      values.every((value) => value != null) ? 'Complete' : 'Missing workflow timestamp',
    ]);
    for (const index of [3, 4, 5, 6]) row.getCell(index).numFmt = '0.0';
  }
  styleSheet(sheet, [22, 15, 20, 18, 16, 17, 28], 'G');
  return sheet;
}

