  snapshotHeader.getCell(5).value = 'Metric';
  snapshotHeader.getCell(6).value = 'Cash';
  snapshotHeader.getCell(7).value = 'Demo';
  snapshotHeader.getCell(8).value = 'Combined';
  for (const index of [5, 6, 7, 8]) {
    snapshotHeader.getCell(index).font = { bold: true, color: { argb: 'FFFFFFFF' } };
    snapshotHeader.getCell(index).fill = {
      type: 'pattern',
      pattern: 'solid',
      fgColor: { argb: 'FF102440' },
    };
  }
  sheet.getCell('E8').value = 'Completed sales';
  sheet.getCell('F8').value = amount(source.completedCashCentavos);
